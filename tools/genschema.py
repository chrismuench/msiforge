"""Harvest the standard MSI table schema out of a WiX-built MSI and emit it as C#.

Running this against a known-good MSI means MsiMaker's baked-in schema is
transcribed from a real Windows Installer database rather than from memory.
"""
import struct, sys
sys.path.insert(0, __import__('os').path.dirname(__file__))
from msidump import read_cfb  # noqa

streams = read_cfb(sys.argv[1])
pool, sdata = streams['!_StringPool'], streams['!_StringData']
n = len(pool) // 4
p = struct.unpack_from('<%dH' % (n * 2), pool, 0)
codepage = p[0] | ((p[1] & ~0x8000) << 16)
sref = 3 if (p[1] & 0x8000) else 2
enc = 'utf-8' if codepage == 65001 else 'cp1252'
strings = {0: ''}
off, i = 0, 1
while i < n:
    ln, refs = p[i*2], p[i*2+1]
    if ln == 0 and refs != 0:
        ln = (refs << 16) | p[i*2+2]; i += 1
    strings[i] = sdata[off:off+ln].decode(enc, 'replace'); off += ln; i += 1

def parse(name, types):
    b = streams['!' + name]
    w = [sref if (t & 0x0800) else (2 if (t & 0xff) == 2 else 4) for t in types]
    rowlen = sum(w)
    rows = len(b) // rowlen if rowlen else 0
    cols, o = [], 0
    for t, ww in zip(types, w):
        vals = []
        for r in range(rows):
            raw = int.from_bytes(b[o + r*ww: o + r*ww + ww], 'little')
            if t & 0x0800: vals.append(strings.get(raw, ''))
            elif ww == 2: vals.append(None if raw == 0 else raw - 0x8000)
            else: vals.append(None if raw == 0 else raw ^ 0x80000000)
        cols.append(vals); o += rows * ww
    return [tuple(c[r] for c in cols) for r in range(rows)]

STR, I2 = 0x0D00 | 72, 0x0102
schema = {}
for t, num, nm, ty in parse('_Columns', [STR, I2, STR, I2]):
    schema.setdefault(t, []).append((num, nm, ty & 0xFFFF))
for t in schema: schema[t].sort()

WANT = ['Property','Directory','Component','File','Feature','FeatureComponents','Media',
        'Registry','Shortcut','RemoveFile','CreateFolder','CustomAction','Icon','Binary',
        'ServiceInstall','ServiceControl','Environment','Upgrade','LaunchCondition',
        'MsiFileHash','Error','AdminExecuteSequence','AdminUISequence','AdvtExecuteSequence',
        'InstallExecuteSequence','InstallUISequence']

out = []
out.append('// <auto-generated> Harvested from a WiX-built MSI by tools/genschema.py.')
out.append('// Column types are transcribed from a real Windows Installer database, not recalled.')
out.append('namespace MsiMaker.Core.Msi;')
out.append('')
out.append('public static partial class MsiSchema')
out.append('{')
out.append('    /// <summary>Standard MSI tables: column name and raw _Columns type word.</summary>')
out.append('    public static readonly Dictionary<string, (string Name, int Type)[]> Standard = new()')
out.append('    {')
missing = []
for t in WANT:
    if t not in schema: missing.append(t); continue
    cols = ', '.join('("%s", 0x%04X)' % (nm, ty) for _, nm, ty in schema[t])
    out.append('        ["%s"] = [%s],' % (t, cols))
out.append('    };')
out.append('}')
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print("tables emitted:", len([t for t in WANT if t in schema]))
if missing: print("NOT PRESENT in sample (need a richer probe):", missing)
print("\n--- sequences actually present (action, condition, seq) ---")
for tbl in ['InstallExecuteSequence', 'InstallUISequence', 'AdvtExecuteSequence',
            'AdminExecuteSequence', 'AdminUISequence']:
    if tbl not in schema: continue
    rows = parse(tbl, [ty for _, _, ty in schema[tbl]])
    print(f"\n{tbl}:")
    for a, c, s in sorted(rows, key=lambda r: r[2] or 0):
        print(f"  {s:>5}  {a}{('   [' + c + ']') if c else ''}")
