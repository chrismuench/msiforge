"""Harvest the standard MSI table schema and action sequences out of a WiX-built
MSI and emit them as C#.

Running this against a known-good MSI means MsiMaker's baked-in schema is
transcribed from a real Windows Installer database rather than from memory.

    python tools/genschema.py <sample.msi> <MsiSchema.Generated.cs> <MsiSequences.Generated.cs>
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from msidump import read_cfb  # noqa: E402

streams = read_cfb(sys.argv[1])
pool, sdata = streams['!_StringPool'], streams['!_StringData']
n = len(pool) // 4
p = struct.unpack_from('<%dH' % (n * 2), pool, 0)
codepage = p[0] | ((p[1] & ~0x8000) << 16)
sref = 3 if (p[1] & 0x8000) else 2
enc = 'utf-8' if codepage == 65001 else 'cp1252'

strings = {0: ''}
off, i = 0, 1
while i < n:
    ln, refs = p[i * 2], p[i * 2 + 1]
    if ln == 0 and refs != 0:
        ln = (refs << 16) | p[i * 2 + 2]
        i += 1
    strings[i] = sdata[off:off + ln].decode(enc, 'replace')
    off += ln
    i += 1


def signed32(v):
    """MSI stores int32 cells biased; bring the result back into signed range."""
    return v - (1 << 32) if v >= (1 << 31) else v


def parse(name, types):
    """Rows of a table. MSI table streams are COLUMN-major."""
    b = streams['!' + name]
    widths = [sref if (t & 0x0800) else (2 if (t & 0xff) == 2 else 4) for t in types]
    rowlen = sum(widths)
    rows = len(b) // rowlen if rowlen else 0
    cols, o = [], 0
    for t, w in zip(types, widths):
        vals = []
        for r in range(rows):
            raw = int.from_bytes(b[o + r * w: o + r * w + w], 'little')
            if t & 0x0800:
                vals.append(strings.get(raw, ''))
            elif raw == 0:
                vals.append(None)
            elif w == 2:
                vals.append(raw - 0x8000)
            else:
                vals.append(signed32(raw ^ 0x80000000))
        cols.append(vals)
        o += rows * w
    return [tuple(c[r] for c in cols) for r in range(rows)]


STR, I2 = 0x0D00 | 72, 0x0102
schema = {}
for table, num, name, ty in parse('_Columns', [STR, I2, STR, I2]):
    schema.setdefault(table, []).append((num, name, ty & 0xFFFF))
for table in schema:
    schema[table].sort()

WANT = ['Property', 'Directory', 'Component', 'File', 'Feature', 'FeatureComponents',
        'Media', 'Registry', 'Shortcut', 'RemoveFile', 'CreateFolder', 'CustomAction',
        'Icon', 'Binary', 'ServiceInstall', 'ServiceControl', 'Environment', 'Upgrade',
        'LaunchCondition', 'MsiFileHash', 'AdminExecuteSequence', 'AdminUISequence',
        'AdvtExecuteSequence', 'InstallExecuteSequence', 'InstallUISequence']

HEADER = [
    '// <auto-generated> Harvested from a WiX-built MSI by tools/genschema.py.',
    '// Transcribed from a real Windows Installer database, not recalled.',
    'namespace MsiMaker.Core.Msi;',
    '',
    'public static partial class MsiSchema',
    '{',
]

# ---------------------------------------------------------------- table schema
out = list(HEADER)
out.append('    /// <summary>Standard MSI tables: column name and raw _Columns type word.</summary>')
out.append('    public static readonly Dictionary<string, (string Name, int Type)[]> Standard = new()')
out.append('    {')
missing = []
for table in WANT:
    if table not in schema:
        missing.append(table)
        continue
    cols = ', '.join('("%s", 0x%04X)' % (nm, ty) for _, nm, ty in schema[table])
    out.append('        ["%s"] = [%s],' % (table, cols))
out.append('    };')
out.append('}')
with open(sys.argv[2], 'w', encoding='utf-8') as fh:
    fh.write('\n'.join(out) + '\n')
print('tables emitted: %d -> %s' % (len(WANT) - len(missing), sys.argv[2]))
if missing:
    print('NOT PRESENT in sample (need a richer probe):', missing)

# ------------------------------------------------------------ action sequences
SEQ_TABLES = ['InstallExecuteSequence', 'InstallUISequence', 'AdminExecuteSequence',
              'AdminUISequence', 'AdvtExecuteSequence']
# Custom actions from the sample are sample-specific, not part of the standard set.
SAMPLE_ONLY = {'CaSet', 'CaExe'}

out = list(HEADER)
out.append('    /// <summary>Standard action sequences: action, condition, sequence number.</summary>')
out.append('    public static readonly Dictionary<string, (string Action, string? Condition, int Sequence)[]> Sequences = new()')
out.append('    {')
total = 0
for table in SEQ_TABLES:
    if table not in schema:
        continue
    rows = parse(table, [ty for _, _, ty in schema[table]])
    rows = [r for r in rows if r[0] not in SAMPLE_ONLY]
    out.append('        ["%s"] =' % table)
    out.append('        [')
    for action, condition, seq in sorted(rows, key=lambda r: r[2] or 0):
        cond = 'null' if not condition else '"%s"' % condition.replace('"', '')
        out.append('            ("%s", %s, %d),' % (action, cond, seq))
        total += 1
    out.append('        ],')
out.append('    };')
out.append('}')
with open(sys.argv[3], 'w', encoding='utf-8') as fh:
    fh.write('\n'.join(out) + '\n')
print('sequence rows emitted: %d -> %s' % (total, sys.argv[3]))

# ---------------------------------------------------------------- _Validation
# Windows Installer consults _Validation when it recreates tables (an
# administrative install does exactly that). Without it, CREATE TABLE fails
# with error 2211 and the install dies at 1603.


def cs_literal(v):
    if v is None:
        return 'null'
    if isinstance(v, int):
        return str(v)
    return '"%s"' % v.replace('\\', '\\\\').replace('"', '\\"')


out = list(HEADER)
cols = schema['_Validation']
out.append('    /// <summary>Column definitions of the _Validation table itself.</summary>')
out.append('    public static readonly (string Name, int Type)[] ValidationColumns =')
out.append('    [')
for _, nm, ty in cols:
    out.append('        ("%s", 0x%04X),' % (nm, ty))
out.append('    ];')
out.append('')
out.append('    /// <summary>_Validation rows for the standard tables MsiMaker emits.</summary>')
out.append('    public static readonly object?[][] ValidationRows =')
out.append('    [')
rows = parse('_Validation', [ty for _, _, ty in cols])
keep = set(WANT)
count = 0
for row in sorted(rows, key=lambda r: (r[0] or '', r[1] or '')):
    if row[0] not in keep:
        continue
    out.append('        [%s],' % ', '.join(cs_literal(v) for v in row))
    count += 1
out.append('    ];')
out.append('}')
with open(sys.argv[4], 'w', encoding='utf-8') as fh:
    fh.write('\n'.join(out) + '\n')
print('_Validation rows emitted: %d -> %s' % (count, sys.argv[4]))
